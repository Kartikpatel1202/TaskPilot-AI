def _clause_domain(clause: str) -> str | None:
    low = clause.lower()
    sites = find_websites(clause)
    if DOWNLOAD_WORD.search(low) or any(s.key == "fx-files" for s in sites):
        return "DOWNLOAD"
    if EMAIL_WORD.search(low) or "draft" in low or any(s.category == "email" for s in sites):
        return "EMAIL"
    if CALENDAR_WORD.search(low) or any(s.category == "calendar" for s in sites):
        return "CALENDAR"
    if any(s.category == "media" and s.key in ("youtube", "fx-youtube") for s in sites) or (MEDIA_WORD.search(low) and not BUY_WORD.search(low)):
        return "YOUTUBE"
    return None


def _target(domain: str, clause: str, text: str) -> str | None:
    if domain == "DOWNLOAD":
        site = next((s for s in find_websites(clause) + find_websites(text) if s.key == "fx-files"), None)
        return site.domain if site else None
    category = _DOMAIN_CATEGORY[domain]
    site = next((s for s in find_websites(clause) if s.category == category), None) or next(
        (s for s in find_websites(text) if s.category == category), None)
    return site.domain if site else _DEFAULT_TARGET[domain]


def _without_sites(text: str, sites: list[Website]) -> str:
    out = text
    for site in sites:
        for alias in site.aliases:
            out = re.sub(r"\s*\b(?:on|in|via|using|par|pe)?\s*" + re.escape(alias) + r"\b", " ", out, flags=re.IGNORECASE)
    return re.sub(r"\s+", " ", out).strip()


def _clean_topic(topic: str | None) -> str | None:
    """Pronouns ("about it") are not a topic; never turn them into a subject line."""
    if not topic:
        return None
    cleaned = topic.strip(" .,!?")
    return None if cleaned.lower() in {"it", "this", "that", "the link", "link", "the video", "the file", "the report", "them"} else cleaned


def workflow_steps(text: str) -> list[dict[str, Any]]:
    """Ordered domain steps when one command spans 2+ integration domains (else [])."""
    clauses = [c.strip(" ,.") for c in _CLAUSE_SPLIT.split(text) if c and c.strip(" ,.")]
    merged: list[tuple[str, str]] = []
    for clause in clauses:
        domain = _clause_domain(clause)
        if domain is None or (merged and merged[-1][0] == domain):
            if merged:
                merged[-1] = (merged[-1][0], merged[-1][1] + " and " + clause)
            continue
        merged.append((domain, clause))
    if len({d for d, _ in merged}) < 2:
        return []
    steps: list[dict[str, Any]] = []
    for index, (domain, clause) in enumerate(merged):
        low = clause.lower()
        step: dict[str, Any] = {"target_website": _target(domain, clause, text), "text": clause[:500], "requested_actions": []}
        if domain == "YOUTUBE":
            step.update(intent="YOUTUBE_PLAYBACK" if PLAY_WORD.search(low) else "YOUTUBE_SEARCH",
                        search_query=_strip_phrases(clause, find_websites(clause))[:300],
                        requested_actions=["search", "play"] if PLAY_WORD.search(low) else ["search"])
        elif domain == "EMAIL":
            recipient = EMAIL_ADDR.search(clause)
            topic = _clean_topic(_topic(_without_sites(clause, find_websites(clause))))
            sending = bool(SEND_WORD.search(low)) and "draft" not in low
            step.update(intent="EMAIL_SEND" if sending else "EMAIL_DRAFT", recipient=recipient.group(0) if recipient else None,
                        message_topic=topic, requested_actions=["send"] if sending else ["draft"],
                        include_previous_output=index > 0 and bool(_PREVIOUS.search(low)))
        elif domain == "CALENDAR":
            title = re.search(r"\b(?:with|for)\s+([A-Za-z][\w ]{1,40}?)(?:\s+(?:at|on|tomorrow|today|kal|aaj|next)\b|$)", clause)
            when = " ".join(m.group(0) for m in (DATE_RE.search(clause), TIME_RE.search(clause)) if m) or None
            step.update(intent="CALENDAR_MANAGEMENT", subject=f"Meeting with {title.group(1).strip()}" if title else "Meeting",
                        datetime_text=when, requested_actions=["create_event"])
        else:
            url = URL_WORD.search(clause)
            step.update(intent="FILE_DOWNLOAD", url=url.group(0) if url else None,
                        search_query=_strip_phrases(re.sub(r"\bdownload\w*\b", " ", URL_WORD.sub(" ", clause), flags=re.IGNORECASE),
                                                    find_websites(clause))[:300],
                        requested_actions=["download"])
        steps.append(step)
    return steps[:8]


