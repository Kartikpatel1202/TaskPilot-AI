def generic_products(text: str, sites: list[Website]) -> list[dict[str, Any]]:
    """Products the built-in vocabulary does not know ("ek shampoo aur ek biscuit"). Each comma/aur/and segment
    that names something short becomes an item; a leading count word sets its quantity. Never invents brands."""
    low = text.lower()
    for site in sites:
        for alias in site.aliases:
            low = low.replace(alias.lower(), " ")
    low = re.sub(r"₹\s*\d+|\brs\.?\s*\d+|\d+\s*(rupees?|rupaye|rs)\b", " ", low)  # prices are not products
    items: list[dict[str, Any]] = []
    for segment in re.split(r",|;|\band\b|\baur\b|\bplus\b|&|और|तथा|\bjaise\b", low):
        words = re.findall(r"[a-zऀ-ॿ0-9]+", segment)
        qty: float | None = None
        for w in words:
            if w in COUNT_WORDS and qty is None:
                qty = float(COUNT_WORDS[w])
            elif w.isdigit() and qty is None and int(w) <= 50:
                qty = float(w)
        name_words = [w for w in words if w not in FILLER and not w.isdigit() and len(w) > 1]
        if not name_words or len(name_words) > 4:
            continue
        if _product_in(" ".join(name_words)):
            continue  # the vocabulary parser already handles it
        name = " ".join(name_words)
        if any(i["name"] == name for i in items):
            continue
        items.append({"name": name, "brand": None, "quantity": qty if qty is not None else 1.0, "unit": "piece" if qty is not None else None,
                      "variant": None, "specs": [], "max_price": None, "category": None})
    return items[:MAX_ITEMS_PER_PLAN + 1]


def _fmt_qty(item: dict[str, Any]) -> str:
    qty, unit = item.get("quantity"), item.get("unit")
    if qty is None:
        return ""
    q = int(qty) if float(qty).is_integer() else qty
    if not unit:
        return str(q)
    return f"{q} {unit}{'s' if unit in ('packet', 'piece', 'bottle') and q != 1 else ''}"


def item_label(item: dict[str, Any]) -> str:
    parts = [item.get("brand") or "", item["name"], _fmt_qty(item)]
    return " ".join(p for p in parts if p).strip()


def _search_text(item: dict[str, Any]) -> str:
    q = _fmt_qty(item) if item.get("unit") in ("litre", "ml", "kg", "g") else ""
    return " ".join(p for p in (item.get("brand") or "", item["name"], q) if p)


def _strip_phrases(text: str, sites: list[Website]) -> str:
    out = text
    for site in sites:
        for alias in site.aliases:
            out = re.sub(re.escape(alias), " ", out, flags=re.IGNORECASE)
    out = re.sub(
        r"\b(open|kholo|khol|and|aur|then|search( for)?|find|look for|dhundo|dhoondo|play|watch|on|par|pe|"
        r"mein|me|please|kamlesh bhai|for me|karo|kar do|chalao|chala do|the best|best)\b|खोजो|पर|में",
        " ",
        out,
        flags=re.IGNORECASE,
    )
    return re.sub(r"\s+", " ", out).strip(" .,!?") or text.strip()


def _topic(text: str) -> str | None:
    m = re.search(
        r"(?:about|regarding|asking about|related to|ke baare mein|ke bare me|ke liye)\s+(.+?)(?:\.|$|,| to \S+@)",
        text,
        re.IGNORECASE,
    )
    if m:
        return m.group(1).strip()[:200]
    m = re.search(r"\b(\w+(?: \w+)?)\s+(?:ka|ki|ke)\s+(?:email|mail)\b", text, re.IGNORECASE)
    return m.group(1).strip()[:200] if m else None


