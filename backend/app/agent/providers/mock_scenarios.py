# ---------------------------------------------------------------------- parsing helpers


def _contains(text: str, alias: str) -> int:
    if alias.isascii():
        m = re.search(rf"(?<![a-z]){re.escape(alias)}(?![a-z])", text)
    else:
        idx = text.find(alias)
        return idx
    return m.start() if m else -1


def _product_in(segment: str) -> str | None:
    best: tuple[int, str] | None = None
    for name, aliases in PRODUCTS.items():
        for alias in aliases:
            pos = _contains(segment, alias)
            if pos >= 0 and (best is None or pos < best[0]):
                best = (pos, name)
    return best[1] if best else None


def _brand_in(segment: str) -> str | None:
    for brand in BRANDS:
        if _contains(segment, brand) >= 0:
            return brand.title() if len(brand) > 3 else brand.upper()
    return None


def _quantity_in(segment: str, product: str) -> tuple[float | None, str | None]:
    seg = re.sub(r"(?<=\d),(?=\d{2,3}\b)", "", segment).replace(",", " ")
    m = None
    for candidate in re.finditer(
        r"(\d+(?:\.\d+)?)\s*(l|ltr|litres?|liters?|ml|kg|kilo|gm?|grams?|packets?|packs?|pkt|dozen|pcs|pieces?|units?|bottles?|लीटर|किलो)?(?![a-z0-9])",
        seg,
    ):
        before = seg[: candidate.start()].rstrip().lower()
        # Prices and budgets ("under ₹60,000") are not quantities.
        if re.search(r"(under|below|less than|upto|up to|within|budget|rs\.?|inr|₹|\$)$", before):
            continue
        if float(candidate.group(1)) > 1000:
            continue
        m = candidate
        break
    if m:
        qty = float(m.group(1))
        unit = UNITS.get((m.group(2) or "").lower())
        if unit is None:
            for tok in re.findall(r"[a-zA-Zऀ-ॿ]+", seg[m.end():]):
                if tok.lower() in UNITS:
                    unit = UNITS[tok.lower()]
                    break
        return _normalise(qty, unit, product)
    tokens = re.findall(r"[a-zA-Zऀ-ॿ]+", seg.lower())
    for i, tok in enumerate(tokens):
        if tok in NUMBER_WORDS and tok != "dozen":
            nxt = tokens[i + 1] if i + 1 < len(tokens) else ""
            # "do"/"a" are only numbers when they qualify a unit, brand or product.
            if tok in ("do", "a", "an") and not (nxt in UNITS or _product_in(nxt) or _brand_in(nxt)):
                continue
            unit = next((UNITS[t] for t in tokens[i + 1 : i + 4] if t in UNITS), None)
            return _normalise(float(NUMBER_WORDS[tok]), unit, product)
        if tok == "dozen":
            return _normalise(1.0, "dozen", product)
    return None, None


def _normalise(qty: float, unit: str | None, product: str) -> tuple[float, str | None]:
    if unit == "dozen":
        return qty * 12, "piece"
    if unit is None and product == "eggs":
        return qty, "piece"
    return qty, unit


def _variant_in(segment: str) -> str | None:
    hits = [(m.start(), v) for v in VARIANT_WORDS if (m := re.search(rf"(?<![a-z]){re.escape(v)}(?![a-z])", segment))]
    if not hits:
        return None
    value = sorted(hits)[0][1]
    return "taaza" if value == "taza" else value


def _specs_in(text: str) -> list[str]:
    out = []
    for m in SPEC_RE.finditer(text):
        kind = m.group(3).upper()
        out.append(f"{m.group(1)}{m.group(2).upper()} {'SSD' if kind in ('SSD', 'HDD', 'STORAGE', 'ROM') and kind != 'RAM' else kind}")
    return list(dict.fromkeys(out))[:4]


def _budget_in(text: str) -> float | None:
    m = BUDGET_RE.search(text)
    if not m:
        return None
    value = float((m.group(1) or m.group(2)).replace(",", ""))
    return value if value >= 100 else None


def parse_products(text: str) -> list[dict[str, Any]]:
    """Extract products with brand/quantity/variant. Later mentions refine earlier ones.

    A segment that states only a quantity ("1 litre" — typically a clarification answer)
    fills the first product still missing its quantity, so answers are never ignored."""
    low = text.lower()
    segments = re.split(r",|;|\band\b|\baur\b|\bplus\b|&|\bwith\b|और|तथा", low)
    items: dict[str, dict[str, Any]] = {}
    for segment in segments:
        product = _product_in(segment)
        if not product:
            if not re.search(r"\d|\b(ek|do|teen|one|two|three|half|aadha)\b|एक|दो|तीन", segment):
                continue
            pending = next((i for i in items.values() if i["quantity"] is None), None)
            if pending is not None:
                qty, unit = _quantity_in(segment, pending["name"])
                if qty is not None and not BUDGET_RE.search(segment):
                    pending["quantity"], pending["unit"] = qty, unit
            continue
        qty, unit = _quantity_in(segment, product)
        brand = _brand_in(segment)
        if product == "apples" and brand == "Apple":
            brand = None  # the fruit, not the phone maker
        item = items.setdefault(product, {"name": product, "brand": None, "quantity": None, "unit": None, "variant": None,
                                          "specs": [], "max_price": None, "category": product if product in ELECTRONICS else None})
        if brand:
            item["brand"] = brand
        variant = _variant_in(segment)
        if variant and not (brand and variant.lower() in brand.lower()):  # "Harvest Gold" is a brand, not the Gold line
            item["variant"] = variant
        if qty is not None:
            item["quantity"], item["unit"] = qty, unit
    specs, budget = _specs_in(low), _budget_in(low)
    for item in items.values():
        if item["name"] in ELECTRONICS:
            item["specs"] = specs or item.get("specs") or []
            item["max_price"] = budget
    return list(items.values())


