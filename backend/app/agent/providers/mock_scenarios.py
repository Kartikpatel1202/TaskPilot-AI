def classify(payload: dict[str, Any]) -> dict[str, Any]:
    command = str(payload.get("command", ""))
    clarifications = [str(c) for c in payload.get("clarifications", [])]
    text = " ".join([command, *clarifications]).strip()
    low = text.lower()
    lang = payload.get("language") or "en"
    context = payload.get("session_context") or {}

    def result(intent: str, confidence: float, **extra: Any) -> dict[str, Any]:
        base: dict[str, Any] = {
            "intent": intent,
            "confidence": confidence,
            "language": lang,
            "target_website": None,
            "entities": {"products": [], "requested_actions": []},
            "missing_information": [],
            "requires_clarification": False,
            "clarification_question": None,
            "is_follow_up": False,
        }
        base.update(extra)
        return base

    if INJECTION.search(text) or DANGEROUS.search(text):
        return result("UNSUPPORTED", 0.97, entities={"products": [], "requested_actions": ["disallowed"]})

    sites = find_websites(text)
    site = sites[0] if sites else None
    ctx_site = lookup(context.get("active_website"))
    follow_up = bool(FOLLOW_UP.search(low)) and bool(context.get("products") or ctx_site)

    if (GREETING.search(low.strip()) or is_small_talk(low)) and not site and not BUY_WORD.search(low) and not OPEN_WORD.search(low) \
            and not parse_products(text):
        return result("GENERAL_CHAT", 0.95)
    if REMEMBER.search(low) and site and not BUY_WORD.search(low.replace("shop", "")):
        return result("GENERAL_CHAT", 0.9, target_website=site.domain)

    # ---------------- Phase 5: one command spanning several integration domains
    steps = workflow_steps(text)
    if steps:
        return result(
            "MULTI_DOMAIN_WORKFLOW", 0.9, target_website=steps[0].get("target_website"),
            entities={"products": [], "workflow": steps, "requested_actions": [s["intent"].lower() for s in steps]},
        )

    # ---------------- email
    if EMAIL_WORD.search(low) or (site and site.category == "email"):
        sending = bool(SEND_WORD.search(low)) and "draft" not in low
        recipient = EMAIL_ADDR.search(text)
        topic = _clean_topic(_topic(_without_sites(text, sites))) or ("internship opportunities" if "internship" in low else None)
        entities = {
            "products": [],
            "recipient": recipient.group(0) if recipient else None,
            "subject": topic.capitalize() if topic else None,
            "message_topic": topic,
            "requested_actions": ["send"] if sending else ["draft"],
        }
        missing = [] if recipient else ["recipient_email"]
        question = None
        if missing:
            who = "HR" if re.search(r"\bhr\b", low) else "the recipient"
            question = say(
                lang,
                f"Sure! What's {who}'s email address? I won't guess it.",
                f"Bilkul bhai! {who} ka email address kya hai? Main andaaza nahi lagaunga.",
                f"ज़रूर! {who} का ईमेल पता क्या है? मैं अंदाज़ा नहीं लगाऊँगा।",
            )
        return result(
            "EMAIL_SEND" if sending else "EMAIL_DRAFT",
            0.93,
            target_website=(site.domain if site and site.category == "email" else "mail.google.com"),
            entities=entities,
            missing_information=missing,
            requires_clarification=bool(missing),
            clarification_question=question,
        )

    # ---------------- calendar
    if CALENDAR_WORD.search(low) or (site and site.category == "calendar"):
        when = " ".join(m.group(0) for m in (DATE_RE.search(text), TIME_RE.search(text)) if m) or None
        missing = [] if (DATE_RE.search(text) and TIME_RE.search(text)) else ["date_and_time"]
        title = re.search(r"\b(?:with|for)\s+([A-Za-z][\w ]{1,40}?)(?:\s+(?:at|on|tomorrow|today|kal|aaj)\b|$)", text)
        return result(
            "CALENDAR_MANAGEMENT",
            0.9,
            target_website=site.domain if site and site.category == "calendar" else "calendar.google.com",
            entities={
                "products": [],
                "datetime_text": when,
                "subject": f"Meeting with {title.group(1).strip()}" if title else "Meeting",
                "requested_actions": ["create_event"],
            },
            missing_information=missing,
            requires_clarification=bool(missing),
            clarification_question=say(
                lang,
                "Which date and time should I schedule it for?",
                "Bhai, kis din aur kitne baje schedule karun?",
                "किस दिन और कितने बजे शेड्यूल करूँ?",
            )
            if missing
            else None,
        )

    # ---------------- download / form / extraction
    if DOWNLOAD_WORD.search(low):
        link = URL_WORD.search(text)
        query = _strip_phrases(re.sub(r"\bdownload\w*\b", " ", URL_WORD.sub(" ", text), flags=re.IGNORECASE), sites)
        missing = [] if (site or link) else ["website"]
        return result(
            "FILE_DOWNLOAD",
            0.86,
            target_website=site.domain if site else None,
            entities={"products": [], "search_query": query, "url": link.group(0) if link else None, "requested_actions": ["download"]},
            missing_information=missing,
            requires_clarification=bool(missing),
            clarification_question=say(
                lang,
                "Which website should I download it from?",
                "Kis website se download karun, bhai?",
            )
            if missing
            else None,
        )
    if FORM_WORD.search(low):
        url = re.search(r"https?://\S+", text)
        missing = [] if (url or site) else ["form_url"]
        return result(
            "FORM_SUBMISSION",
            0.82,
            target_website=site.domain if site else None,
            entities={"products": [], "url": url.group(0) if url else None, "requested_actions": ["fill", "submit"]},
            missing_information=missing,
            requires_clarification=bool(missing),
            clarification_question=say(lang, "Which form should I fill? Please share its link.", "Kaunsa form bharna hai? Link de do.")
            if missing
            else None,
        )
    if EXTRACT_WORD.search(low) and site:
        return result(
            "DATA_EXTRACTION",
            0.84,
            target_website=site.domain,
            entities={"products": [], "search_query": _strip_phrases(text, sites), "requested_actions": ["extract"]},
        )

    # ---------------- media
    if (site and site.category == "media") or (MEDIA_WORD.search(low) and not BUY_WORD.search(low)):
        media_site = site if site and site.category == "media" else WEBSITES[7]  # YouTube
        query = _strip_phrases(text, sites)
        return result(
            "MEDIA_SEARCH",
            0.94,
            target_website=media_site.domain,
            entities={
                "products": [],
                "search_query": query,
                "requested_actions": ["search", "play"] if PLAY_WORD.search(low) else ["search"],
            },
        )

    # ---------------- commerce
    products = parse_products(text)
    commerce_site = site if site and site.category in ("grocery", "ecommerce") else None
    shop_ctx = ctx_site if ctx_site and ctx_site.category in ("grocery", "ecommerce") else None
    shopping_words = bool(BUY_WORD.search(low))
    if commerce_site and not products and not shopping_words and OPEN_WORD.search(low) and not SEARCH_WORD.search(low):
        return result("BROWSER_NAVIGATION", 0.93, target_website=commerce_site.domain, entities={"products": [], "requested_actions": ["open"]})
    if not products and (commerce_site or shopping_words or (shop_ctx and context.get("active_intent") == "ECOMMERCE_SHOPPING")):
        products = generic_products(text, sites)
    if not site and shop_ctx and products and not follow_up and context.get("active_intent") == "ECOMMERCE_SHOPPING":
        follow_up = True  # a bare product list answering "what should I add?" belongs to the same store
    preferred = lookup((payload.get("user_profile") or {}).get("preferred_store"))
    if not commerce_site and not shop_ctx and preferred and (products or shopping_words):
        commerce_site = preferred  # Settings: preferred store when the request names none
    payment = "COD" if COD_WORD.search(low) else ("PREPAID" if PREPAID_WORD.search(low) else None)
    review_site = commerce_site or (ctx_site if ctx_site and ctx_site.category in ("grocery", "ecommerce") else None)
    if review_site and not products and (CHECKOUT_REVIEW_WORD.search(low) or CART_REVIEW_WORD.search(low)):
        checkout = bool(CHECKOUT_REVIEW_WORD.search(low))
        return result(
            "ECOMMERCE_CHECKOUT_REVIEW" if checkout else "ECOMMERCE_CART_REVIEW", 0.9, target_website=review_site.domain,
            entities={"products": context.get("products") or [], "requested_actions": ["checkout_review" if checkout else "cart_review"],
                      "payment_preference": payment},
        )
    if follow_up and not commerce_site:
        commerce_site = ctx_site
    if follow_up:
        products = _merge_follow_up(context.get("products") or [], products, low)
    is_commerce = bool(commerce_site) or bool(products) or bool(BUY_WORD.search(low))
    if is_commerce:
        shopping = bool(BUY_WORD.search(low)) or (follow_up and context.get("active_intent") == "ECOMMERCE_SHOPPING")
        if not shopping and SEARCH_WORD.search(low):
            m = re.search(r"(?:find|search(?: for)?|look for|dhundo|show)\s+(?:me\s+)?(?:an?\s+)?(.+?)(?:\s+on\s+\w+|\s*$)", text, re.IGNORECASE)
            query = (m.group(1) if m else _strip_phrases(text, sites)).strip(" .")
            return result(
                "ECOMMERCE_SEARCH",
                0.92,
                target_website=commerce_site.domain if commerce_site else None,
                entities={"products": products, "search_query": query, "requested_actions": ["search", "compare"]},
                missing_information=[] if commerce_site else ["website"],
                requires_clarification=not commerce_site,
                clarification_question=None
                if commerce_site
                else say(lang, "Which store should I search on — Amazon or Flipkart?", "Kis store pe dhundhun — Amazon ya Flipkart?"),
            )
        wants_order = (bool(ORDER_WORD.search(low)) and not re.search(r"\bcart\b|कार्ट", low)) or bool(
            re.search(r"place (the |this |my )?order|order (place )?kar\w*", low))
        actions = ["add_to_cart"] + (["place_order"] if wants_order else []) + (["payment"] if PAY_WORD.search(low) else [])
        missing: list[str] = []
        if not commerce_site:
            missing.append("website")
        if not products:
            missing.append("products")
        for item in products:
            if item["name"] in MEASURED and item.get("quantity") is None:
                if item.get("brand") is None and "brand" not in missing:
                    missing.append("brand")
                if "quantity" not in missing:
                    missing.append("quantity")
        if len(products) > MAX_ITEMS_PER_PLAN:
            missing.append("fewer_items")
        question = _shopping_question(lang, missing, products) if missing else None
        return result(
            "ECOMMERCE_SHOPPING",
            0.95 if not missing else 0.8,
            target_website=commerce_site.domain if commerce_site else None,
            entities={"products": products, "requested_actions": actions, "payment_preference": payment},
            missing_information=missing,
            requires_clarification=bool(missing),
            clarification_question=question,
            is_follow_up=follow_up,
        )

    if site and OPEN_WORD.search(low):
        return result("BROWSER_NAVIGATION", 0.9, target_website=site.domain, entities={"products": [], "requested_actions": ["open"]})

    return result("GENERAL_CHAT", 0.6)


def _merge_follow_up(previous: list[dict[str, Any]], new: list[dict[str, Any]], low: str) -> list[dict[str, Any]]:
    merged = [dict(p) for p in previous]
    by_name = {p["name"]: p for p in merged}
    if not new and merged:
        target = merged[-1]
        variants = [(m.start(), v) for v in VARIANT_WORDS if (m := re.search(rf"(?<![a-z]){re.escape(v)}(?![a-z])", low))]
        if variants:
            wanted = [v for pos, v in sorted(variants) if not NEGATION.search(low[pos: pos + len(v) + 12])]
            if wanted:
                target["variant"] = "taaza" if wanted[0] == "taza" else wanted[0]
                return merged
        m = re.search(r"quantity (?:to|ko) (\w+)", low)
        if m:
            word = m.group(1)
            value = float(word) if word.replace(".", "", 1).isdigit() else NUMBER_WORDS.get(word)
            if value:
                target["quantity"] = value
        elif re.search(r"\b(one more|ek aur|aur ek)\b", low):
            target["quantity"] = (target.get("quantity") or 1) + 1
        return merged
    for item in new:
        if item["name"] in by_name:
            existing = by_name[item["name"]]
            for key in ("brand", "quantity", "unit", "variant", "max_price"):
                if item.get(key) is not None:
                    existing[key] = item[key]
            if item.get("specs"):
                existing["specs"] = item["specs"]
        else:
            merged.append(item)
            by_name[item["name"]] = item
    return merged


