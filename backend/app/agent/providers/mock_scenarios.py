class _Steps:
    def __init__(self) -> None:
        self.items: list[dict[str, Any]] = []

    def add(
        self, action: dict[str, Any], description: str, outcome: str, risk: str = "LOW", approval: bool = False
    ) -> int:
        order = len(self.items) + 1
        self.items.append(
            {
                "order": order,
                "action": action,
                "description": description,
                "expected_outcome": outcome,
                "risk_level": risk,
                "requires_approval": approval,
                "depends_on_orders": [order - 1] if order > 1 else [],
            }
        )
        return order

    def gate(self, reason: str, risk: str, details: list[dict[str, str]]) -> None:
        self.add(
            {"type": "request_approval", "reason": reason, "risk_level": risk, "details": details},
            "Ask for your explicit approval before continuing.",
            "Execution pauses until you approve or reject.",
            risk,
            True,
        )


def _draft(status: str, summary: str, message: str, confidence: float, steps: _Steps | None = None,
           assumptions: list[str] | None = None, question: str | None = None, missing: list[str] | None = None) -> dict[str, Any]:
    return {
        "status": status,
        "summary": summary,
        "user_facing_message": message,
        "confidence": confidence,
        "assumptions": [*(assumptions or []), MOCK_NOTE],
        "clarification_question": question,
        "missing_information": missing or [],
        "steps": steps.items if steps else [],
    }


def plan(payload: dict[str, Any]) -> dict[str, Any]:
    intent = payload.get("intent") or {}
    lang = payload.get("language") or intent.get("language") or "en"
    kind = intent.get("intent", "UNSUPPORTED")
    entities = intent.get("entities") or {}
    site = lookup(intent.get("target_website"))

    if intent.get("requires_clarification"):
        q = intent.get("clarification_question") or say(lang, "Could you share a bit more detail?", "Bhai, thoda aur detail doge?")
        return _draft("NEEDS_CLARIFICATION", "More information is needed before planning.", q, intent.get("confidence", 0.7),
                      question=q, missing=intent.get("missing_information"))

    if kind == "UNSUPPORTED":
        disallowed = "disallowed" in (entities.get("requested_actions") or [])
        msg = (
            say(lang, "Sorry, I can't help with that. I only plan safe, supported browser tasks — and I never reveal system details.",
                "Sorry bhai, ye main nahi kar sakta. Main sirf safe aur supported browser tasks plan karta hoon.",
                "माफ़ कीजिए, यह मैं नहीं कर सकता। मैं केवल सुरक्षित, समर्थित ब्राउज़र कार्य ही प्लान करता हूँ।")
            if disallowed
            else say(lang, "I can't plan that yet. Try shopping, searching, YouTube, email drafts or calendar tasks.",
                     "Ye abhi mere bas ka nahi hai bhai. Shopping, search, YouTube, email draft ya calendar wale kaam bolo.",
                     "यह अभी मैं प्लान नहीं कर सकता। शॉपिंग, सर्च, YouTube, ईमेल ड्राफ्ट या कैलेंडर के काम बताइए।")
        )
        return _draft("REJECTED", "Request is outside supported capabilities.", msg, intent.get("confidence", 0.9))

    if kind == "GENERAL_CHAT":
        if site:
            msg = say(lang, f"Noted! I'll use {site.name} for this session.", f"Done bhai! Is session mein {site.name} yaad rakhunga.",
                      f"ठीक है! इस सेशन में {site.name} याद रखूँगा।")
        else:
            profile = payload.get("user_profile") or {}
            msg = small_talk_reply(str(payload.get("command", "")), lang, profile.get("display_name") or None)
        return _draft("READY", "Conversation — no browser actions needed.", msg, 0.95)

    builder = {
        "ECOMMERCE_SHOPPING": _plan_shopping,
        "ECOMMERCE_SEARCH": _plan_search,
        "MEDIA_SEARCH": _plan_media,
        "EMAIL_DRAFT": _plan_email,
        "EMAIL_SEND": _plan_email,
        "CALENDAR_MANAGEMENT": _plan_calendar,
        "FILE_DOWNLOAD": _plan_download,
        "FORM_SUBMISSION": _plan_form,
        "DATA_EXTRACTION": _plan_extract,
        "BROWSER_NAVIGATION": _plan_navigate,
    }.get(kind)
    if builder is None or site is None and kind not in ("FORM_SUBMISSION",):
        return _draft("REJECTED", "Request could not be planned.", say(lang, "I couldn't work out where to do this.", "Bhai, samajh nahi aaya ye kahan karna hai."), 0.5)
    return builder(lang, site, entities, intent)


def _open(steps: _Steps, site: Website) -> None:
    steps.add({"type": "navigate", "url": site.base_url, "purpose": f"Open {site.name}"},
              f"Navigate to {site.name}.", f"{site.name} is opened.")


